/**
 * @file    app.h
 * @brief   Бизнес-логика: тест радиоканала FSK (передатчик или приёмник).
 *
 * Переносимый код: не зависит ни от микроконтроллера, ни от радиочипа.
 * Использует только bsp_* из board.h и printf. Весь вывод в терминал делает только app.
 */

#ifndef APP_H
#define APP_H

#include <stdint.h>

/* ------------------------------------------------------------------------- */
/* Режим работы: выбирается одним define                                     */
/* ------------------------------------------------------------------------- */

#define APP_MODE_TX 1 /* передатчик */
#define APP_MODE_RX 2 /* приёмник   */

/* Меняется здесь или ключом компилятора -DAPP_MODE=APP_MODE_RX */
#ifndef APP_MODE
#define APP_MODE APP_MODE_TX
#endif

/* ------------------------------------------------------------------------- */
/* Параметры теста                                                           */
/* ------------------------------------------------------------------------- */

/* Длина полезной нагрузки передатчика, байт: 4..255 (первые 4 байта - номер пакета).
 * При длинных пакетах и скорости 2 Мбит/с приёмнику может не хватать времени
 * вычитать FIFO до начала следующего пакета; 128 - безопасное значение. */
#ifndef APP_TX_PAYLOAD_LEN
#define APP_TX_PAYLOAD_LEN 128u
#endif

/* Период начала передач, мс. 0 = слать пакеты подряд (максимальная скорость). */
#ifndef APP_TX_PERIOD_MS
#define APP_TX_PERIOD_MS 0u
#endif

/* Период вывода сводки (и окно измерения скорости), мс. */
#ifndef APP_STATS_PERIOD_MS
#define APP_STATS_PERIOD_MS 1000u
#endif

/* 1 = печатать строку на каждый пакет. Только для отладки на малых скоростях:
 * UART 115200 блокирует цикл, при потоке пакетов приёмник начнёт их терять. */
#ifndef APP_LOG_EVERY_PACKET
#define APP_LOG_EVERY_PACKET 0
#endif

/* 1 = в сводку приёмника добавлять счётчики самого чипа (лишний SPI-обмен раз в период). */
#ifndef APP_LOG_CHIP_STATS
#define APP_LOG_CHIP_STATS 0
#endif

/* ------------------------------------------------------------------------- */
/* Интерфейс                                                                 */
/* ------------------------------------------------------------------------- */

/** @brief Точка входа. Не возвращает управление. */
void app(void);

/** @brief Напечатать строку из qnt символов ch. */
void setSeparator(char ch, uint8_t qnt);

#endif /* APP_H */
